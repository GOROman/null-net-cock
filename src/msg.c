/* 「!X」→ 制御文字 (X - 0x40)、「!@」→「!」 */
static void unescape(char *s) {
    char *w = s;
    for (char *r = s; *r; r++) {
        if (*r == '!' && r[1]) {
            r++;
            *w++ = *r == '@' ? '!' : (char)(*r - 0x40);
        } else *w++ = *r;
    }
    *w = 0;
}

static char *sjis_to_utf8(const char *in) {
    iconv_t cd = iconv_open("UTF-8", "CP932");
    size_t il = strlen(in), ol = il * 3 + 1;
    char *out = calloc(1, ol), *op = out, *ip = (char *)in;
    if (cd != (iconv_t)-1) {
        iconv(cd, &ip, &il, &op, &ol);
        iconv_close(cd);
    }
    return out;
}

static int load_into(const char *path, char **table) {
    FILE *f = fopen(path, "rb");
    if (!f) return -1;
    char line[4096];
    int id = 0;
    while (fgets(line, sizeof line, f) && id < NMSG) {
        line[strcspn(line, "\r\n")] = 0;
        if (line[0] == '*') continue;
        if (line[0] == '!' && line[1] == '!') break;
        char *u = sjis_to_utf8(line);
        unescape(u);
        table[id++] = u;
    }
    fclose(f);
    return id;
}

int msg_load(const char *path) { return load_into(path, loaded); }
int msg_load_esc(const char *path) { return load_into(path, loaded_esc); }

const char *M(int id) {
    if (id < 0 || id >= NMSG) return "";
    if (use_esc && loaded_esc[id]) return loaded_esc[id];
    if (loaded[id]) return loaded[id];
    static char *esc_fallback[NMSG];
    if (!fallback[id]) return "";
    if (!esc_fallback[id]) {
        esc_fallback[id] = strdup(fallback[id]);
        unescape(esc_fallback[id]);
    }
    return esc_fallback[id];
}

/* SYS_MES.DAT: 1 行 128 バイト (Shift_JIS、NUL 詰め)、1 メッセージ 10 行、「.」の行で終わり */
int sysmes_load(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) return -1;
    int n = 0;
    for (int i = 0; i < 10; i++) {
        char text[1400] = "";
        bool ended = false;
        int got = 0;
        for (int l = 0; l < 10; l++) {
            char rec[129] = {0};
            if (fread(rec, 1, 128, f) != 128) break;
            got++;
            if (ended) continue;
            if (!strcmp(rec, ".")) {
                ended = true;
                continue;
            }
            if (strlen(text) + strlen(rec) + 2 < sizeof text) {
                if (l > 0) strcat(text, "\n");
                strcat(text, rec);
            }
        }
        if (got < 10) break;
        char *u = sjis_to_utf8(text);
        snprintf(g_sys.sysmes[i], sizeof g_sys.sysmes[i], "%s", u);
        free(u);
        n++;
    }
    fclose(f);
    return n;
}
